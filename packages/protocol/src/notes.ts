/**
 * Shared durable project-notes index schema (schema v1).
 *
 * Note bodies are Markdown files and deliberately never appear in this index.
 * The browser and Host use this exact strict decoder; unlike board workspace
 * paths, note paths are always root-relative POSIX paths, so validation needs
 * no platform-specific predicate and this module stays browser-safe.
 *
 * @module @yankeguo/dsh-devlead-protocol
 */

import { z as zod } from 'zod'
import type { ZodType } from 'zod'
import { DEVLEAD_BOARD_READ_MAX_BYTES } from './board.ts'

/** Current on-disk notes-index schema version. */
export const DEVLEAD_NOTES_SCHEMA_VERSION = 1
/** Directory beside `board.json` that contains the notes index and Markdown files. */
export const DEVLEAD_NOTES_DIR_NAME = 'notes'
/** Notes index filename inside {@link DEVLEAD_NOTES_DIR_NAME}. */
export const DEVLEAD_NOTES_INDEX_FILE_NAME = 'index.json'
/** Maximum serialized index size (128 KiB); larger files are never decoded. */
export const DEVLEAD_NOTES_INDEX_MAX_BYTES = 128 * 1024
/** Maximum UTF-8 size of one stored Markdown note (256 KiB). */
export const DEVLEAD_NOTES_NOTE_MAX_BYTES = 256 * 1024
/** Maximum serialized size of one model-facing single-note read (64 KiB). */
export const DEVLEAD_NOTES_READ_MAX_BYTES = DEVLEAD_BOARD_READ_MAX_BYTES
/** Maximum project entries in one notes index (matching the board limit). */
export const DEVLEAD_NOTES_MAX_PROJECTS = 50
/** Maximum note metadata rows in one project. */
export const DEVLEAD_NOTES_MAX_PER_PROJECT = 100
/** Maximum UTF-16 code units in a board-project or note id. */
export const DEVLEAD_NOTES_ID_MAX = 128
/** Maximum UTF-16 code units in a Host-generated project directory segment. */
export const DEVLEAD_NOTES_DIRECTORY_MAX = 128
/** Maximum UTF-16 code units in a note title. */
export const DEVLEAD_NOTES_TITLE_MAX = 200
/** Maximum UTF-16 code units in a note summary. */
export const DEVLEAD_NOTES_SUMMARY_MAX = 500
/** Maximum UTF-16 code units in a root-relative note path. */
export const DEVLEAD_NOTES_PATH_MAX = 512
/** Maximum UTF-16 code units in a timestamp string before ISO parsing. */
export const DEVLEAD_NOTES_TIMESTAMP_MAX = 64

/** Metadata of one Markdown note; its body is stored only at {@link path}. */
export interface DevLeadNoteMetadata {
  id: string
  title: string
  summary: string
  updatedAt: string
  bytes: number
  /** Root-relative POSIX path: `<directory>/<note-id>.md`. */
  path: string
}

/** Notes owned by one board project. The project id is the original board id. */
export interface DevLeadNotesProject {
  id: string
  /** Sanitized, collision-safe single path segment generated by the Host. */
  directory: string
  notes: DevLeadNoteMetadata[]
}

/** Complete durable notes index. */
export interface DevLeadNotesIndex {
  schemaVersion: 1
  revision: number
  updatedAt: string
  projects: DevLeadNotesProject[]
}

const timestampSchema = zod.string().max(DEVLEAD_NOTES_TIMESTAMP_MAX).pipe(zod.iso.datetime())
const projectIdSchema = zod.string().min(1).max(DEVLEAD_NOTES_ID_MAX)
const titleSchema = zod.string().min(1).max(DEVLEAD_NOTES_TITLE_MAX)
const summarySchema = zod.string().max(DEVLEAD_NOTES_SUMMARY_MAX)

const WINDOWS_RESERVED_NAMES = new Set([
  'CON', 'PRN', 'AUX', 'NUL',
  ...Array.from({ length: 9 }, (_, index) => `COM${index + 1}`),
  ...Array.from({ length: 9 }, (_, index) => `LPT${index + 1}`),
])

/** Match Win32 device names even with an extension or trailing spaces/dots. */
function isWindowsReservedName(value: string): boolean {
  const normalized = value.replace(/[. ]+$/gu, '')
  const basename = normalized.split('.', 1)[0]?.replace(/ +$/gu, '').toUpperCase() ?? ''
  return WINDOWS_RESERVED_NAMES.has(basename)
}

/**
 * Filename-safe ids keep the note body beneath its generated project directory.
 * A UUID fits this grammar; caller-supplied ids may also use dots, underscores,
 * and dashes after an alphanumeric first character.
 */
const noteIdSchema = projectIdSchema.regex(/^[A-Za-z0-9][A-Za-z0-9._-]*$/u, {
  message: 'note id must start with an alphanumeric and contain only alphanumerics, dot, underscore, or dash',
}).refine(value => !isWindowsReservedName(value), {
  message: 'note id must not be a Windows reserved device name',
})
const directorySchema = zod.string().min(1).max(DEVLEAD_NOTES_DIRECTORY_MAX)
  .regex(/^[a-z0-9][a-z0-9._-]*$/u, {
    message: 'directory must be a sanitized lowercase POSIX segment',
  })
  .refine(value => value !== '.' && value !== '..', {
    message: 'directory must not be a traversal segment',
  })
  .refine(value => !isWindowsReservedName(value), {
    message: 'directory must not be a Windows reserved device name',
  })

const relativePathSchema = zod.string().min(1).max(DEVLEAD_NOTES_PATH_MAX)
  .refine(value => !value.includes('\\'), { message: 'note path must use POSIX separators' })
  .refine(value => !value.startsWith('/'), { message: 'note path must be relative to the notes root' })
  .refine(value => value.split('/').every(segment => segment.length > 0 && segment !== '.' && segment !== '..'), {
    message: 'note path must not contain empty or traversal segments',
  })

const noteSchema = zod.object({
  id: noteIdSchema,
  title: titleSchema,
  summary: summarySchema,
  updatedAt: timestampSchema,
  bytes: zod.number().int().nonnegative().max(DEVLEAD_NOTES_NOTE_MAX_BYTES),
  path: relativePathSchema,
}).strict()

const projectSchema = zod.object({
  id: projectIdSchema,
  directory: directorySchema,
  notes: zod.array(noteSchema).max(DEVLEAD_NOTES_MAX_PER_PROJECT),
}).strict()

const indexSchema = zod.object({
  schemaVersion: zod.literal(DEVLEAD_NOTES_SCHEMA_VERSION),
  revision: zod.number().int().nonnegative().safe(),
  updatedAt: timestampSchema,
  projects: zod.array(projectSchema).max(DEVLEAD_NOTES_MAX_PROJECTS),
}).strict().superRefine((index, context) => {
  const projectIds = new Set<string>()
  const directories = new Set<string>()
  const paths = new Set<string>()
  index.projects.forEach((project, projectIndex) => {
    if (projectIds.has(project.id)) {
      context.addIssue({
        code: 'custom', path: ['projects', projectIndex, 'id'],
        message: `duplicate project id "${project.id}"`,
      })
    }
    projectIds.add(project.id)
    if (directories.has(project.directory)) {
      context.addIssue({
        code: 'custom', path: ['projects', projectIndex, 'directory'],
        message: `duplicate project directory "${project.directory}"`,
      })
    }
    directories.add(project.directory)
    const noteIds = new Set<string>()
    project.notes.forEach((note, noteIndex) => {
      const portableId = note.id.toLowerCase()
      if (noteIds.has(portableId)) {
        context.addIssue({
          code: 'custom', path: ['projects', projectIndex, 'notes', noteIndex, 'id'],
          message: `duplicate note id "${note.id}" ignoring case`,
        })
      }
      noteIds.add(portableId)
      const expectedPath = `${project.directory}/${note.id}.md`
      if (note.path !== expectedPath) {
        context.addIssue({
          code: 'custom', path: ['projects', projectIndex, 'notes', noteIndex, 'path'],
          message: `note path must be "${expectedPath}"`,
        })
      }
      const portablePath = note.path.toLowerCase()
      if (paths.has(portablePath)) {
        context.addIssue({
          code: 'custom', path: ['projects', projectIndex, 'notes', noteIndex, 'path'],
          message: `duplicate note path "${note.path}" ignoring case`,
        })
      }
      paths.add(portablePath)
    })
  })
})

/**
 * Build the strict schema-v1 decoder shared by Host and browser.
 *
 * Unknown fields, duplicate project ids, case-insensitive duplicate note
 * ids/paths, Windows reserved device names, duplicate directories, malformed
 * timestamps, unsafe path spellings, and metadata paths that do not exactly
 * match their project directory and note id are all rejected.
 */
export function createDevLeadNotesIndexSchema(): ZodType<DevLeadNotesIndex> {
  return indexSchema as unknown as ZodType<DevLeadNotesIndex>
}

/** Parse one already-JSON-decoded notes index with the shared strict schema. */
export function parseDevLeadNotesIndex(value: unknown): DevLeadNotesIndex {
  return createDevLeadNotesIndexSchema().parse(value)
}
